#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
# Turns DeepFilterNet3's released ONNX export into core/src/DeepFilterNet3Weights.cpp
# (half-precision floats in the order DeepFilter.cpp's Weights::bind() reads them).
#
#   pip install onnx numpy
#   python3 make_weights_source.py DeepFilterNet3_onnx.tar.gz ../../core/src/DeepFilterNet3Weights.cpp
#
# DeepFilterNet3_onnx.tar.gz is in the models/ folder of
# https://github.com/Rikorose/DeepFilterNet (MIT or Apache-2.0).
import io, sys, tarfile
import numpy as np, onnx
from onnx import numpy_helper

ORDER = ['enc.conv0.w','enc.conv0.b','enc.conv1.w','enc.conv2.w','enc.conv2.b','enc.conv3.w','enc.conv4.w','enc.conv4.b',
 'enc.conv5.w','enc.conv6.w','enc.conv6.b','enc.conv7.w','enc.conv8.w','enc.conv8.b','enc.conv9.w','enc.conv10.w','enc.conv10.b',
 'enc.lin0','enc.lin1','enc.gru0.W','enc.gru0.R','enc.gru0.B','enc.lin2','enc.mm0','enc.mmb0',
 'erb.lin0','erb.gru0.W','erb.gru0.R','erb.gru0.B','erb.gru1.W','erb.gru1.R','erb.gru1.B','erb.lin1',
 'erb.conv0.w','erb.conv0.b','erb.conv1.w','erb.conv2.w','erb.conv2.b','erb.conv3.w','erb.conv3.b','erb.convt4.w','erb.conv5.w','erb.conv5.b',
 'erb.conv6.w','erb.conv6.b','erb.convt7.w','erb.conv8.w','erb.conv8.b','erb.conv9.w','erb.conv9.b','erb.conv10.w','erb.conv10.b',
 'df.lin0','df.gru0.W','df.gru0.R','df.gru0.B','df.gru1.W','df.gru1.R','df.gru1.B','df.lin1','df.conv0.w','df.conv1.w','df.conv1.b','df.lin2']

def graph_weights(model, prefix, W):
    g = model.graph
    vals = {i.name: numpy_helper.to_array(i) for i in g.initializer}
    for n in g.node:
        if n.op_type == 'Constant':
            for a in n.attribute:
                if a.name == 'value':
                    vals[n.output[0]] = numpy_helper.to_array(a.t)
    ci = gi = ei = mi = 0
    for n in g.node:
        if n.op_type in ('Conv', 'ConvTranspose'):
            key = f'{prefix}.{"convt" if n.op_type == "ConvTranspose" else "conv"}{ci}'; ci += 1
            W[key + '.w'] = vals[n.input[1]]
            if len(n.input) > 2 and n.input[2]:
                W[key + '.b'] = vals[n.input[2]]
        elif n.op_type == 'GRU':
            key = f'{prefix}.gru{gi}'; gi += 1
            W[key + '.W'] = vals[n.input[1]][0]; W[key + '.R'] = vals[n.input[2]][0]; W[key + '.B'] = vals[n.input[3]][0]
        elif n.op_type == 'Einsum':
            W[f'{prefix}.lin{ei}'] = vals[n.input[1]]; ei += 1
        elif n.op_type == 'MatMul':
            W[f'{prefix}.mm{mi}'] = vals[n.input[1]]; mi += 1
        elif n.op_type == 'Add':
            for i in n.input:
                if i in vals and vals[i].size == 1 and 'bias' in i:
                    W[f'{prefix}.mmb{mi - 1}'] = vals[i]

def main():
    W = {}
    with tarfile.open(sys.argv[1]) as tf:
        for m in tf.getmembers():
            for name, prefix in (('enc.onnx', 'enc'), ('erb_dec.onnx', 'erb'), ('df_dec.onnx', 'df')):
                if m.name.endswith('/' + name) or m.name == name:
                    graph_weights(onnx.load_model_from_string(tf.extractfile(m).read()), prefix, W)
    blob = np.concatenate([W[k].astype(np.float32).ravel() for k in ORDER]).astype(np.float16)
    words = blob.view(np.uint16)
    with open(sys.argv[2], 'w') as f:
        f.write('// SPDX-License-Identifier: MIT OR Apache-2.0\n')
        f.write('// DeepFilterNet3 weights (c) Hendrik Schroeter and contributors, from\n')
        f.write('// https://github.com/Rikorose/DeepFilterNet (MIT or Apache-2.0).\n')
        f.write('// Generated by tools/deepfilter/make_weights_source.py: half-precision\n')
        f.write('// floats in the order DeepFilter.cpp reads them. Do not edit.\n')
        f.write('#include <cstddef>\n#include <cstdint>\n\nnamespace mend {\n\n')
        f.write(f'extern const std::size_t kDeepFilterNet3WeightCount = {len(words)};\n')
        f.write('extern const std::uint16_t kDeepFilterNet3Weights[];\n')
        f.write('const std::uint16_t kDeepFilterNet3Weights[] = {\n')
        for i in range(0, len(words), 16):
            f.write(','.join(f'0x{w:04x}' for w in words[i:i + 16]) + ',\n')
        f.write('};\n\n} // namespace mend\n')
    print(len(words), 'weights')

if __name__ == '__main__':
    main()
